-- Bind each GitHub installation to the App that created it, and give
-- repository connections a way to record that the App installation no longer
-- grants access to them.
--
-- An installation_id is only meaningful to the GitHub App it was created
-- under. Rotating GITHUB_APP_ID silently orphans every stored installation:
-- the row keeps status='active' but token minting fails with an opaque 404.
-- Recording app_id lets callers detect the mismatch before they ever call
-- GitHub.

-- Nullable on purpose. Rows written before this migration predate the binding,
-- and we cannot know which App they belong to. NULL means "unverified" and must
-- stay readable; back-filling a guessed app_id would assert a binding we never
-- observed, and deleting the rows would drop live installations.
ALTER TABLE github_installations
    ADD COLUMN IF NOT EXISTS app_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_github_installations_app_id
    ON github_installations(app_id);

-- Set when a repository disappears from the App installation, so the
-- connection can be hidden from the UI without losing its indexing history.
ALTER TABLE repository_connections
    ADD COLUMN IF NOT EXISTS revoked_at TIMESTAMPTZ;

-- Widen the status domain to include 'revoked'. A CHECK constraint cannot be
-- altered in place, so it has to be dropped and re-added.
--
-- 002 declared this constraint inline and unnamed, so its name was generated by
-- PostgreSQL rather than chosen by us. Matching on the column it guards instead
-- of on that generated name means a database built by any other path still gets
-- widened rather than silently ending up with two constraints, the older of
-- which would keep rejecting 'revoked'. The re-add pins the canonical name so
-- later migrations can refer to it directly.
--
-- The DO block is one statement, so the drop and the re-add commit together and
-- concurrent writers never observe repository_connections unconstrained.
-- github_installations_status_check already permits 'revoked' and is left alone.
DO $$
DECLARE
    status_attnum SMALLINT;
    stale_constraint TEXT;
BEGIN
    SELECT attnum INTO STRICT status_attnum
    FROM pg_attribute
    WHERE attrelid = 'repository_connections'::regclass
      AND attname = 'status'
      AND NOT attisdropped;

    FOR stale_constraint IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'repository_connections'::regclass
          AND contype = 'c'
          AND conkey = ARRAY[status_attnum]
    LOOP
        EXECUTE format(
            'ALTER TABLE repository_connections DROP CONSTRAINT %I',
            stale_constraint
        );
    END LOOP;

    ALTER TABLE repository_connections
        ADD CONSTRAINT repository_connections_status_check
        CHECK (status IN ('connected', 'disabled', 'archived', 'error', 'revoked'));
END $$;

DO $$ BEGIN
    RAISE NOTICE 'OpsPilot installation/app binding migration complete';
END $$;
